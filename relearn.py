"""Regenerate the learned data modules from weekly files:  learned_drivers.py, school_routes.py, rate_book.py.
Usage: edit WEEKS below (or import and call relearn(weeks, folder)) and run  python relearn.py <folder>"""
import sys, os
import pandas as pd
import app_logic as AL, classification as C, ratebook as RB

TRUST = ["state report", "driver map", "main file hint", "Oregon school"]


def relearn(weeks, folder, write=True):
    rb = lambda f: open(os.path.join(folder, f), "rb").read()
    recs, votes, drivers, conflicts = [], {}, {}, []
    for w in weeks:
        r = AL.process_uploads([(f, rb(f)) for f in w["main"]], [(f, rb(f)) for f in w["state"]], state_overrides=w.get("overrides"))
        if len(r.main):
            t = r.main[r.main.state_source.isin(TRUST)]; C._add_votes(votes, t.state, t.trip_key)
        s = r.st[r.st.trip_key.ne("")] if len(r.st) else r.st
        if len(s): C._add_votes(votes, s.state_hint, s.trip_key)
        if len(r.rec): recs.append(r.rec)
        for d, sts in C.driver_evidence(r.st).items():
            if len(sts) == 1:
                new = next(iter(sts))
                if d in drivers and drivers[d] != new: conflicts.append((d, drivers[d], new))
                drivers[d] = new                                  # most recent report wins
    base = C.base_map_normalised.__wrapped__() if hasattr(C.base_map_normalised, "__wrapped__") else None
    from config import BASE_DRIVER_STATE
    from normalization import norm_name
    bk = {norm_name(k): v for k, v in BASE_DRIVER_STATE.items()}
    learned = {d: s for d, s in drivers.items() if d not in bk}
    book = RB.build(recs) if recs else None
    if write:
        with open("learned_drivers.py", "w") as f:
            f.write("# Drivers learned from uploaded state reports (not in the original map). Original map wins; uploaded state reports always win. Regenerated by relearn.py\nLEARNED_DRIVER_STATE = {\n")
            f.write("".join(f"    {d!r}: {s!r},\n" for d, s in sorted(learned.items())) + "}\n")
        with open("school_routes.py", "w") as f:
            f.write("# School (route) -> state knowledge from trusted trips (state reports, driver map, file hints). Regenerated by relearn.py\nSCHOOL_STATE = {\n")
            f.write("".join(f"    {k!r}: {dict(sorted(v.items()))!r},\n" for k, v in sorted(votes.items())) + "}\n")
        if book: RB.write_module(book)
    return {"learned": learned, "conflicts": conflicts, "schools": len(votes), "book": book, "recs": recs}


WEEKS = [
    {"main": ["First_all_states_.xlsx", "First_Alaska.xlsx", "Ever_driven_Nebraska.PDF"],
     "state": ["4__AK__24-30_OCT_.xlsx", "ABQ_Payments__Oct_26th_to_Oct_30th_.xlsx", "IL_Report.xlsx", "North_CA__26th_-_30th_October_2026.xlsx",
               "Oregon_26th_-_30th_Oct_2026.xlsx", "S_CA.xlsx", "NE_Report-Nov_3rd.xlsx"]},
    {"main": ["Frist_All_States.xlsx"],
     "state": ["North_CA__2nd_-_6th_Novemeber_2026.xlsx", "RS___AZ_Nov_2_-_6.xlsx", "Kansas_Report-Nov_3rd.xlsx",
               "ABQ_Payments__Nov_2nd_to_Nov_6th_.xlsx", "Oregon_02ND_-_06TH_Nov_2026.xlsx"]},
]

if __name__ == "__main__":
    out = relearn(WEEKS, sys.argv[1] if len(sys.argv) > 1 else ".")
    print(len(out["learned"]), "learned drivers;", out["schools"], "school stems; conflicts:", out["conflicts"])
