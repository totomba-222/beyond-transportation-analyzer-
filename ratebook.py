"""Rate book: contract price (Beyond revenue) and driver pay per route, learned from state reports; used to (1) check what
First/EverDriven paid against the contract price BEFORE the state report arrives and (2) give a clearly-labelled ESTIMATE of
driver payments / profit when a state report is missing. Estimates are never mixed into the actual state-report figures."""
import re
import numpy as np
import pandas as pd
from normalization import norm_name, norm_trip


def route_key(name):
    """'Tyson ES OB 05 ER 102826 01' -> 'tyson es ob 05';  'Wendler MS IB 02 (M)' -> 'wendler ms ib 02';  'Muldoon ES IB 01_A' -> 'muldoon es ib 01'."""
    s = re.sub(r"\([^)]*\)", " ", str(name))
    s = re.sub(r"\b(?:er|ls)\s+\d{6}\s+\d{2}\b", " ", s, flags=re.I)
    s = re.sub(r"(?<=\d)_[a-z]\b", " ", s, flags=re.I)
    return norm_trip(s)


def _counts(s):
    s = pd.Series(s).dropna().round(2)
    return {float(k): int(v) for k, v in s.value_counts().items()}


def _mode(d, min_share=0.8, min_n=1):
    if not d: return None
    tot = sum(d.values()); v = max(d, key=d.get)
    return (v, d[v] / tot, tot) if d[v] / tot >= min_share and tot >= min_n else None


def build(recs):
    df = pd.concat(recs, ignore_index=True)
    df = df[df.state_revenue.notna() & df.trip_name.fillna("").ne("") & df.state.notna() & ~df.state.isin(["Unassigned", "NEEDS REVIEW"])].copy()
    df["route"] = df.trip_name.map(route_key); df["mi"] = df.main_miles.fillna(df.state_miles)
    df["dk"] = df.driver.map(norm_name)
    routes, miles, drv_route, drv = {}, {}, {}, {}
    for (st, rt), g in df.groupby(["state", "route"]):
        routes[f"{st}|{rt}"] = {"rev": _counts(g.state_revenue), "pay": _counts(g.driver_payment), "mi": float(g.mi.median()) if g.mi.notna().any() else None}
    m = df[df.mi.notna()]
    for (st, mi), g in m.groupby(["state", m.mi.round().astype(int)]):
        miles[f"{st}|{mi}"] = {"rev": _counts(g.state_revenue), "pay": _counts(g.driver_payment)}
    p = df[df.driver_payment.notna()]
    for (d, rt), g in p.groupby(["dk", "route"]):
        mo = _mode(_counts(g.driver_payment))
        if mo: drv_route[f"{d}|{rt}"] = mo[0]
    for d, g in p.groupby("dk"): drv[d] = _counts(g.driver_payment)
    return {"routes": routes, "miles": miles, "driver_route_pay": drv_route, "driver_pay": drv}


def write_module(book, path="rate_book.py"):
    def fmt(d): return "{\n" + "".join(f"    {k!r}: {v!r},\n" for k, v in sorted(d.items())) + "}"
    with open(path, "w") as f:
        f.write("# Rate book learned from state reports (contract price = Beyond revenue per trip; driver pay). Regenerated by relearn.py\n")
        for k in ("routes", "miles", "driver_route_pay", "driver_pay"): f.write(f"{k.upper()} = {fmt(book[k])}\n")


def load():
    import rate_book as rb
    return {"routes": rb.ROUTES, "miles": rb.MILES, "driver_route_pay": rb.DRIVER_ROUTE_PAY, "driver_pay": rb.DRIVER_PAY}


def expected(book, state, trip_name, miles, driver=None):
    """-> dict(rev, rev_src, pay, pay_src). Sources: 'route' (same route learned) | 'miles' (same state+miles, >=5 trips) | None."""
    rt = route_key(trip_name); out = {"rev": np.nan, "rev_src": "", "pay": np.nan, "pay_src": ""}
    e = book["routes"].get(f"{state}|{rt}")
    r = _mode(e["rev"], 0.8, 2) if e else None
    if r: out.update(rev=r[0], rev_src="route")
    elif pd.notna(miles):
        mt = book["miles"].get(f"{state}|{int(round(miles))}"); r = _mode(mt["rev"], 0.8, 5) if mt else None
        if r: out.update(rev=r[0], rev_src="miles")
    dk = norm_name(driver) if driver else None
    if dk and f"{dk}|{rt}" in book["driver_route_pay"]: out.update(pay=book["driver_route_pay"][f"{dk}|{rt}"], pay_src="driver+route")
    else:
        p = _mode(e["pay"], 0.8, 2) if e else None
        if p: out.update(pay=p[0], pay_src="route")
        elif dk and book["driver_pay"].get(dk) and _mode(book["driver_pay"][dk], 0.9, 3): out.update(pay=_mode(book["driver_pay"][dk], 0.9, 3)[0], pay_src="driver")
        elif pd.notna(miles):
            mt = book["miles"].get(f"{state}|{int(round(miles))}"); p = _mode(mt["pay"], 0.7, 5) if mt else None
            if p: out.update(pay=p[0], pay_src="miles")
    return out


def annotate(main, book):
    ex = [expected(book, s, t, mi, d) for s, t, mi, d in zip(main.state, main.trip_name, main.miles, main.driver_disp)]
    e = pd.DataFrame(ex, index=main.index)
    return main.join(e.rename(columns={"rev": "exp_revenue", "rev_src": "exp_rev_src", "pay": "exp_pay", "pay_src": "exp_pay_src"}))
